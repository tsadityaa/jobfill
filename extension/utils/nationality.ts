function normalizeCountry(country: string): string {
  return country
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

/**
 * Convert a country name to its nationality ("India" → "Indian").
 * Returns the country unchanged when it is not in the dictionary, so the
 * caller still has a sensible value to fill.
 */
export function countryToNationality(country: string | undefined): string | undefined {
  const trimmed = country?.trim();
  if (!trimmed) return undefined;

  const normalized = normalizeCountry(trimmed);
  const key = COUNTRY_ALIASES[normalized] ?? normalized;
  return COUNTRY_TO_NATIONALITY[key] ?? trimmed;
}
